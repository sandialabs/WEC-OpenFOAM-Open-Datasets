#!/bin/bash
#------------------------------------------------------------------------------------------#
# Script to extract pressure and discharge data from postProcessing folders
# Usage: ./extractQP.sh OF_case_directory
# Output: PQ.txt will be placed inside the specified OF_case_directory/postProcessing
# Note: the provided plotPQ.py can be used to visualize the results.
#------------------------------------------------------------------------------------------#
QoIs=('p0' 'p1' 'volFlow')
folder='postProcessing'
flowParams='flowParams'

# Create header
echo '*************************Generated by extractQP.sh*************************'  >> header
echo -e "*      $(date). Case: $dir"                                                >> header
echo '* Note: Outputs can be visualized with plotQP.py'                             >> header
echo '***************************************************************************'  >> header
echo "Time(s) p0(Pa) p1(Pa) Q(m3/s)"        >> header

# Loop through input folders and extract volume flow rate and pressure
for dir in "$@"
do
    first=0
    # Extract user-input porous parameters
    porousSettings=$dir/$folder/'porousSettings.dat'
    grep "DarcyCoeff" $dir/$flowParams  | tr -d ';' > $porousSettings
    grep "inertiaCoeff" $dir/$flowParams  | tr -d ';' >> $porousSettings
    grep "baffle_dL" $dir/$flowParams | tr -d ';' >> $porousSettings

    # Extract output data
    fileOut=$dir/$folder/'QP.dat'
    for qoi in "${QoIs[@]}"
    do
        file=$dir/$folder/$qoi'/0/surfaceFieldValue.dat'
        if [ $first -eq 0 ]; then
            # Pressure and time values
            sed -r '/^#/d' $file | awk '{print $1, $2}' > $qoi'Temp'
            
            # Extract porous zone area
            grep "Area" $file | head -n 1 | tr -d ':#' >> $porousSettings 
            first=1
        else
            sed -r '/^#/d' $file | awk '{print $2}' > $qoi'Temp'
        fi
    done
    paste -d' ' *'Temp' > output

    cat header output > $fileOut

    for qoi in "${QoIs[@]}"
    do
        rm $qoi'Temp'
    done
    rm output
done

rm header



